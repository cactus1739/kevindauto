function p(code: number, name: string, category: Category, series = 'Đời thường'): Product {
  const normalizedName = name.charAt(0).toLocaleLowerCase('vi') + name.slice(1)
  return {
    id: `sp-${code}`,
    code: `${code}`,
    name,
    category,
    series,
    price: 30000,
    material: 'Resin 3D cao cấp',
    rating: 5,
    reviews: 20 + (code % 30),
    badge: 'Mới',
    inStock: true,
    accent: accents[category],
    image: `./products/sp-${code}.webp`,
    tags: [...new Set([category, series.toLocaleLowerCase('vi'), ...normalizedName.toLocaleLowerCase('vi').split(/\s+/)])],
    description: `Mô hình ${normalizedName} với tạo hình rõ nét, phù hợp trưng bày và dựng diorama chủ đề ${series.toLocaleLowerCase('vi')}.`,
    highlights: ['Tạo hình nhân vật tự nhiên', 'Chi tiết sắc nét', 'Phù hợp trưng bày và dựng diorama'],
  }
}

